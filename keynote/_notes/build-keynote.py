#!/usr/bin/env python3
"""Write keynote/keynote.html, the talk deck, from keynote/keynote_extended.html.

keynote_extended.html is the one file to edit. keynote.html is the same deck with the
reserve slides (every <section> carrying data-reserve) and the Reserves banner comment
taken out. Run after every edit to the extended deck, and commit both files together:

    python3 keynote/_notes/build-keynote.py          # write keynote.html
    python3 keynote/_notes/build-keynote.py --check  # fail if keynote.html is stale
"""
import re
import sys
from pathlib import Path

KEYNOTE = Path(__file__).resolve().parent.parent
SRC = KEYNOTE / "keynote_extended.html"
OUT = KEYNOTE / "keynote.html"

GENERATED = (
    "<!-- GENERATED from keynote_extended.html by keynote/_notes/build-keynote.py.\n"
    "     Do not edit this file: edit keynote_extended.html and run the script. -->\n"
)


def build(html: str) -> tuple[str, int]:
    # The banner comments that open the Reserves and the Template samples.
    html, n_banner = re.subn(
        r"\n[ \t]*<!-- =+\s*\n\s*(?:Reserves|Template samples) .*?-->[ \t]*\n", "\n", html, flags=re.S
    )
    # Every reserve slide. Sections do not nest in this deck, so the first </section>
    # after an opening tag closes it.
    pattern = re.compile(
        r"\n?[ \t]*<section\b[^>]*\bdata-reserve=\"[^\"]*\"[^>]*>.*?</section>[ \t]*\n", re.S
    )
    html, n_reserve = pattern.subn("\n", html)
    if n_banner != 2 or n_reserve == 0:
        sys.exit(f"build-keynote: expected the Reserves and Template samples banners and some reserve slides, "
                 f"found {n_banner} and {n_reserve}; the deck's layout changed, fix the script")
    if "data-reserve=" in re.sub(r"<script>.*?</script>|/\*.*?\*/|<!--.*?-->", "", html, flags=re.S):
        sys.exit("build-keynote: a data-reserve attribute survived outside the script")
    html = html.replace("<!doctype html>\n", "<!doctype html>\n" + GENERATED, 1)
    # Collapse the blank lines left where the reserves were.
    html = re.sub(r"\n{3,}(\s*</div>\s*\n\s*<div class=\"notes-panel\")", r"\n\n\1", html)
    return html, n_reserve


def main() -> None:
    html, n_reserve = build(SRC.read_text(encoding="utf-8"))
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != html:
            sys.exit("build-keynote: keynote.html is stale; run keynote/_notes/build-keynote.py")
        print("build-keynote: keynote.html is up to date")
        return
    OUT.write_text(html, encoding="utf-8")
    slides = len(re.findall(r'<section class="slide', re.sub(r"<!--.*?-->|/\*.*?\*/", "", html, flags=re.S)))
    print(f"build-keynote: wrote {OUT.name}: {slides} slides, {n_reserve} reserve slides left out")


if __name__ == "__main__":
    main()
