// Read every commit of the cloned public repositories (all branches, tags and pull request heads),
// de-duplicate by hash across repositories, and mark the ones that carry direct evidence of an AI
// coding agent. Writes commits.json beside this script.
//
//   clones/<org>_<repo>.git   made with:
//     git clone --bare --filter=blob:none https://github.com/<org>/<repo>.git
//     git fetch origin '+refs/pull/*/head:refs/pull/*/head'
//   node ai-adoption-commits.mjs
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import { REPOS } from './ai-adoption-repos.mjs';

const dir = new URL('.', import.meta.url).pathname;
const git = (gd, args) => execFileSync('git', ['--git-dir=' + gd, ...args], { encoding: 'utf8', maxBuffer: 1 << 30 });

// An AI tool named as author or co-author. Checked against the distinct names and addresses found (printed below).
export const AI_NAME = /\b(claude|anthropic|copilot|cursor ?agent|cursoragent|codex|openai|chatgpt|gemini|devin-ai-integration|aider|jules|windsurf|codeium|amazon q)\b/i;
// Automation that is not an AI agent: dependency and workflow bots.
export const PLAIN_BOT = /\[bot\]|^dependabot|^github-actions|^actions-user|noreply@github\.com$/i;

const seen = new Map();   // sha -> record (first repo that had it wins)
const perRepo = {};
for (const full of REPOS) {
  const gd = `${dir}clones/${full.replace('/', '_')}.git`;
  if (!fs.existsSync(gd)) { console.error('missing clone', full); process.exit(1); }
  const onDefault = new Set(git(gd, ['rev-list', 'HEAD']).split('\n').filter(Boolean));
  const out = git(gd, ['log', '--all', '--no-merges', '--format=%H%x1f%aI%x1f%cI%x1f%an%x1f%ae%x1f%cn%x1f%ce%x1f%B%x1e']);
  let n = 0, fresh = 0;
  for (const rec of out.split('\x1e')) {
    const f = rec.replace(/^\n/, '').split('\x1f');
    if (f.length < 8) continue;
    n++;
    const [sha, ad, cd, an, ae, cn, ce, msg] = f;
    if (seen.has(sha)) { if (onDefault.has(sha)) seen.get(sha).on_default = true; continue; }
    fresh++;
    const co = [...msg.matchAll(/^\s*co-authored-by:\s*(.+)$/gim)].map(m => m[1].trim());
    const aiCo = co.filter(c => AI_NAME.test(c));
    const aiAuthor = AI_NAME.test(an) || AI_NAME.test(ae);
    const aiFooter = /generated with \[?claude code|🤖 generated with|generated by (github )?copilot|\bcodex\b.*generated/i.test(msg);
    const plainBot = !aiAuthor && (PLAIN_BOT.test(an) || PLAIN_BOT.test(ae));
    // A Copilot review suggestion or autofix accepted in the browser: GitHub is the committer and the subject is the
    // one GitHub writes ("Update <file>", "Apply suggestions from code review", "Potential fix for ..."). These are
    // small edits a person clicked to accept, not code an agent was asked to write, and are counted apart.
    const subject = msg.split('\n')[0];
    const suggestion = aiCo.length > 0 && ce === 'noreply@github.com' && /^(update \S+$|apply .*suggestions?\b|potential fix for)/i.test(subject);
    seen.set(sha, { sha, repo: full, author_date: new Date(ad).toISOString(), commit_date: new Date(cd).toISOString(), an, ae, cn, ce, on_default: onDefault.has(sha), co, ai_co: aiCo, ai_author: aiAuthor, ai_footer: aiFooter, plain_bot: plainBot, suggestion, subject: msg.split('\n')[0].slice(0, 120) });
  }
  perRepo[full] = { commits_non_merge_all_refs: n, new_to_the_set: fresh, default_branch: git(gd, ['symbolic-ref', '--short', 'HEAD']).trim() };
  console.log(full, JSON.stringify(perRepo[full]));
}
const commits = [...seen.values()];
const tally = (arr, key) => { const o = {}; for (const x of arr) o[key(x)] = (o[key(x)] || 0) + 1; return Object.entries(o).sort((a, b) => b[1] - a[1]); };
const since = commits.filter(c => c.author_date >= '2025-01-01');
console.log('\nunique non-merge commits', commits.length, 'authored since 2025-01-01', since.length);
console.log('\nAI co-author values since 2025:', tally(since.flatMap(c => c.ai_co), x => x));
console.log('\nOther co-author values since 2025 (top 40):', tally(since.flatMap(c => c.co.filter(v => !AI_NAME.test(v))), x => x.replace(/<.*>/, '<…>')).slice(0, 40));
console.log('\nAI author names since 2025:', tally(since.filter(c => c.ai_author), c => c.an + ' <' + c.ae + '>'));
console.log('\nPlain bot authors since 2025:', tally(since.filter(c => c.plain_bot), c => c.an + ' <' + c.ae.replace(/^\d+\+/, '') + '>'));
console.log('\nAI-marked since 2025:', since.filter(c => c.ai_co.length || c.ai_author).length, 'of which accepted suggestions:', since.filter(c => c.suggestion).length);
console.log('\nfooter only (no trailer, no AI author):', since.filter(c => c.ai_footer && !c.ai_co.length && !c.ai_author).length);
// A second count of the trailers, straight from git's own search, to compare with the parsing above.
const grepSeen = new Map();
for (const full of REPOS) {
  const gd = `${dir}clones/${full.replace('/', '_')}.git`;
  for (const l of git(gd, ['log', '--all', '--no-merges', '-i', '-E', '--grep=^[[:space:]]*co-authored-by:.*(claude|copilot|anthropic)', '--format=%H %aI']).split('\n').filter(Boolean)) { const [h, d] = l.split(' '); grepSeen.set(h, new Date(d).toISOString()); }
}
const inWin = d => d >= '2025-01-01' && d < '2026-10-07';
const second = { command: "git log --all --no-merges -i -E --grep='^[[:space:]]*co-authored-by:.*(claude|copilot|anthropic)' --format='%H %aI', per clone, unique hashes, author date 2025-01-01 to 2026-10-06", git_grep_count: [...grepSeen.values()].filter(inWin).length, parsed_count: commits.filter(c => c.ai_co.length > 0 && inWin(c.author_date)).length };
second.match = second.git_grep_count === second.parsed_count;
console.log('\nsecond count of AI co-author trailers:', JSON.stringify(second));
fs.writeFileSync(dir + 'commits.json', JSON.stringify({ made: new Date().toISOString(), per_repo: perRepo, second_count: second, commits }));
